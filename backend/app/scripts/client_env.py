"""
Shared helpers for provision_client and upgrade_clients (docs/deployment.md).

A client is a name like "client_a". It has one env file, clients/<name>.env,
holding that client's backend settings, and one database + database user,
both named after the client. Nothing here imports the app's database
settings, so these helpers work for any client's DATABASE_URL.
"""
import os
import re
import secrets
import subprocess
import sys
from pathlib import Path

from dotenv import dotenv_values

BACKEND_DIR = Path(__file__).resolve().parent.parent.parent
CLIENTS_DIR = BACKEND_DIR.parent / "clients"

# Also used as the PostgreSQL database and user name
CLIENT_NAME = re.compile(r"^[a-z][a-z0-9_]{1,39}$")


class StepError(Exception):
    """A provisioning or upgrade step failed."""


def check_client_name(name: str) -> str:
    if not CLIENT_NAME.match(name):
        raise StepError(
            f"Invalid client name '{name}': use 2-40 lowercase letters, digits and "
            "underscores, starting with a letter (it becomes the database name)."
        )
    return name


def env_path(name: str, clients_dir: Path = CLIENTS_DIR) -> Path:
    return clients_dir / f"{name}.env"


def client_env_files(clients_dir: Path = CLIENTS_DIR) -> list[Path]:
    """Every client's env file, sorted by name (example.env is a template, not a client)."""
    return sorted(p for p in clients_dir.glob("*.env") if p.name != "example.env")


def read_env(path: Path) -> dict[str, str]:
    values = {key: value for key, value in dotenv_values(path).items() if value is not None}
    if not values.get("DATABASE_URL"):
        raise StepError(f"{path.name} has no DATABASE_URL")
    return values


def new_env(
    name: str,
    db_host: str,
    cors_origin: str,
    gemini_api_key: str = "",
) -> str:
    """
    Contents of a new client env file, with a fresh database password and
    SECRET_KEY. db_host is "host" or "host:port".
    """
    password = secrets.token_urlsafe(24)
    if ":" not in db_host:
        db_host += ":5432"
    return (
        f"# Backend settings for client '{name}' (generated by provision_client).\n"
        "# Keep this file secret. The SECRET_KEY must be unique per client, so that\n"
        "# one client's login tokens are rejected by every other client.\n"
        f"DATABASE_URL=postgresql+psycopg://{name}:{password}@{db_host}/{name}\n"
        f"SECRET_KEY={secrets.token_urlsafe(48)}\n"
        "ALGORITHM=HS256\n"
        "ACCESS_TOKEN_EXPIRE_MINUTES=60\n"
        f"GEMINI_API_KEY={gemini_api_key}\n"
        f"CORS_ORIGINS={cors_origin}\n"
        "DB_POOL_SIZE=2\n"
        "DB_MAX_OVERFLOW=3\n"
    )


def run_step(title: str, args: list[str], client_env: dict[str, str]) -> None:
    """
    Run `python <args>` from backend/ with the client's settings, the same way
    its backend container runs. Raises StepError when the command fails.
    """
    print(f"\n-- {title}", flush=True)
    env = {**os.environ, **client_env}
    result = subprocess.run([sys.executable, *args], cwd=BACKEND_DIR, env=env)
    if result.returncode != 0:
        raise StepError(f"{title} failed (exit code {result.returncode})")
